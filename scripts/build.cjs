const fs = require('node:fs');
const core = fs.readFileSync('src/core.luau', 'utf8').trimEnd();
const runtime = fs.readFileSync('src/runtime.luau', 'utf8').trimEnd();
const result = '-- Generated by npm run build. Edit core.luau and runtime.luau.\n'
  + 'local Core = (function()\n' + core + '\nend)()\n\n' + runtime + '\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync('src/main.client.luau', 'utf8').replace(/\r\n/g, '\n') !== result.replace(/\r\n/g, '\n')) {
    throw new Error('Bundle is stale. Run npm run build.');
  }
} else fs.writeFileSync('src/main.client.luau', result);
